import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = dirname(fileURLToPath(import.meta.url));
const parts = await Promise.all(['adapters.js', 'page-hook.js'].map(file => readFile(join(root, file), 'utf8')));
// Chromium deduplicates a content-script file reused in MAIN and ISOLATED.
// Use a distinct generated resource for MAIN, preserving a single source of truth.
await writeFile(join(root, 'capture-main.js'), '// Generated by node build.mjs. Do not edit.\n' + parts.join('\n;\n'));
console.log('Built capture-main.js');
